#!/usr/bin/env bash
# repo-health.sh — GENERATED inventory of every git repo/worktree under $HOME.
#
# This is the single source of truth for repo state. Nothing else should restate
# it — MEMORY.md, skills, and CLAUDE.md files should POINT here. A pointer cannot
# rot; a copy always does.
#
# Three checks only, deliberately:
#   1. unbacked commits  (ground truth: rev-list --not --remotes, NOT tracking config)
#   2. dirty trees       (worktrees scanned separately — they are missed otherwise)
#   3. repos with no reachable remote
#
# Written 2026-07-21 after an audit in which seven wrong conclusions were reached
# by trusting documents instead of the machine. Every check here is one that would
# have caught at least one of them.

set -uo pipefail
ROOT="${1:-$HOME}"
OUT="${REPO_HEALTH_OUT:-$HOME/websites/INVENTORY.md}"
STAMP=$(date +%Y-%m-%d)

# maxdepth 5, not 3: at depth 3 this tool could not see
# ~/.claude/projects/-home-coke/memory (depth 5) — which turned out to be the dirtiest
# and longest-unbacked repo on the machine. A health check with a blind spot is worse
# than none, because it reports "all clean" about the part it cannot see.
#
# But depth 5 also drags in third-party checkouts nobody owns (AUR build caches, tmux
# plugins, tool snapshots). Those turned one real finding into 43 rows of noise. A report
# that is mostly noise gets ignored, which is the same failure as not running it. Prune
# anything not authored here.
EXCLUDES=( '*/node_modules/*' '*/attic/*' '*/.cache/*' '*/.deepseek/*' '*/.tmux/plugins/*'
           '*/.local/share/*' '*/.npm/*' '*/go/pkg/*' '*/.vscode*/*' '*/.venv/*' )
repos() {
  local args=(); for e in "${EXCLUDES[@]}"; do args+=( -not -path "$e" ); done
  find "$ROOT" -maxdepth 5 -name .git "${args[@]}" -printf '%h\n' 2>/dev/null | sort -u
}

problems=0
rows=""
while read -r d; do
  [ -n "$d" ] || continue
  name="${d#"$HOME"/}"
  branch=$(git -C "$d" branch --show-current 2>/dev/null)
  dirty=$(git -C "$d" status --porcelain 2>/dev/null | wc -l | tr -d ' ')
  remote=$(git -C "$d" remote 2>/dev/null | head -1)

  if [ -z "$remote" ]; then
    has_commits=$(git -C "$d" rev-list -n1 --all 2>/dev/null)
    if [ -n "$has_commits" ]; then
      unbacked="NO REMOTE"; problems=$((problems+1))
    else
      unbacked="empty"        # bare `git init`, nothing to lose
    fi
  else
    # A narrowed fetch refspec makes --not --remotes lie: branches with no local
    # tracking ref look unbacked when they are on origin. Flag it rather than
    # silently reporting a false positive.
    if ! git -C "$d" config --get-all remote.origin.fetch 2>/dev/null | grep -q 'refs/heads/\*'; then
      unbacked="REFSPEC NARROWED"; problems=$((problems+1))
    else
      unbacked=$(git -C "$d" rev-list --count --branches --not --remotes 2>/dev/null)
      [ "${unbacked:-0}" != "0" ] && problems=$((problems+1))
    fi
  fi
  [ "$dirty" != "0" ] && problems=$((problems+1))

  flag=""
  [ "$dirty" != "0" ] && flag="dirty"
  case "$unbacked" in 0|empty) ;; *) flag="${flag:+$flag, }UNBACKED" ;; esac
  rows+="| \`$name\` | $branch | $dirty | $unbacked | ${flag:-ok} |"$'\n'
done < <(repos)

{
  echo "# Repo Inventory — generated $STAMP"
  echo
  echo "Generated by \`~/bin/repo-health.sh\`. **Do not hand-edit.** Do not restate this"
  echo "content in MEMORY.md, skills, or CLAUDE.md files — link here instead."
  echo
  echo "| repo / worktree | branch | dirty | unbacked | status |"
  echo "|---|---|---:|---|---|"
  printf '%s' "$rows"
  echo
  echo "**Problems: $problems**"
  echo
  echo "\`UNBACKED\` = commits reachable from no origin ref. \`NO REMOTE\` = nothing is"
  echo "backed up anywhere. \`REFSPEC NARROWED\` = fetch refspec is not \`refs/heads/*\`,"
  echo "so the unbacked count cannot be trusted; fix with:"
  echo '`git config --replace-all remote.origin.fetch "+refs/heads/*:refs/remotes/origin/*"`'
} > "$OUT"

printf '%s\n' "$rows" | grep -v '| ok |' | sed 's/^/  /' || true
echo
echo "repo-health: $problems problem(s). Full inventory -> $OUT"
[ "$problems" -eq 0 ] && echo "  all clean." || true
exit 0
