#!/usr/bin/env bash

# ==============================================================================
# STARSHIP PATH BREADCRUMBS SCRIPT
# ==============================================================================
# Outputs ANSI escape code path pills for the starship custom.path module.
# Mirrors the tmux path_pills.sh style using ANSI codes instead of tmux format.
# ==============================================================================

# --- POWERLINE GLYPHS (hex escapes to survive file saves) ---
LEFT_CAP=$'\xEE\x82\xBA'    # U+E0BA slanted left opening
SEPARATOR=$'\xEE\x82\xB4'   # U+E0B4 between-pill connector
RIGHT_CAP=$'\xEE\x82\xB4'   # U+E0B4 closing right cap
ICON=$'\xF3\xB0\x86\x8D'    # U+F018D MDI console

# --- COLOR PALETTE ---
# Sourced from ~/.config/theme/colors.sh, generated by matugen from
# theme/matugen/config.toml, so the prompt follows a palette switch. Falls back
# to Marigold if the generated file is missing.
if [[ -r "${XDG_CONFIG_HOME:-$HOME/.config}/theme/colors.sh" ]]; then
    # shellcheck source=/dev/null
    source "${XDG_CONFIG_HOME:-$HOME/.config}/theme/colors.sh"
fi

TEXT_RGB="${THEME_BG_RGB:-26;22;20}"        # text inside pills
ICON_RGB="${THEME_ORANGE_RGB:-255;107;53}"  # icon pill

SEGMENT_COLORS=(
    "${THEME_BLUE_RGB:-255;140;66}"
    "${THEME_CYAN_RGB:-127;176;160}"
    "${THEME_MAGENTA_RGB:-224;135;155}"
    "${THEME_GREEN_RGB:-163;181;101}"
    "${THEME_YELLOW_RGB:-250;189;47}"
    "${THEME_ORANGE_RGB:-255;107;53}"
    "${THEME_RED_RGB:-242;84;61}"
)

# Darker variants (~70%), alternating with SEGMENT_COLORS so each pill edge is
# visible. Computed from the base colours rather than hardcoded: the previous
# hardcoded list was never updated during the Tokyo Night -> Marigold swap and
# was still emitting Tokyo Night blues underneath Marigold pills.
SEGMENT_COLORS_DARK=()
for _seg in "${SEGMENT_COLORS[@]}"; do
    IFS=';' read -r _r _g _b <<< "$_seg"
    SEGMENT_COLORS_DARK+=( "$(( _r * 70 / 100 ));$(( _g * 70 / 100 ));$(( _b * 70 / 100 ))" )
done
unset _seg _r _g _b

NUM_COLORS=${#SEGMENT_COLORS[@]}

# --- PATH PROCESSING ---
PATH_DISPLAY="${PWD/$HOME/\~}"

IFS='/' read -ra PATH_PARTS <<< "$PATH_DISPLAY"

FINAL_SEGMENTS=()
for segment in "${PATH_PARTS[@]}"; do
    [[ -n "$segment" ]] && FINAL_SEGMENTS+=("$segment")
done

[[ -z "${FINAL_SEGMENTS[*]}" ]] && FINAL_SEGMENTS+=("/")

# --- ICON PILL ---
# Left cap in icon color on transparent bg
printf "\e[38;2;${ICON_RGB}m\e[49m%s" "$LEFT_CAP"
# Icon content: icon-color bg, dark text, bold
printf "\e[48;2;${ICON_RGB}m\e[38;2;${TEXT_RGB}m\e[1m %s " "$ICON"

# --- PATH SEGMENTS ---
count=0
last_rgb="$ICON_RGB"

for segment in "${FINAL_SEGMENTS[@]}"; do
    color_idx=$((count / 2 % NUM_COLORS))
    if (( count % 2 == 0 )); then
        cur_rgb="${SEGMENT_COLORS[$color_idx]}"
    else
        cur_rgb="${SEGMENT_COLORS_DARK[$color_idx]}"
    fi

    # Powerline separator — fg = prev color, bg = current color
    printf "\e[38;2;${last_rgb}m\e[48;2;${cur_rgb}m%s" "$SEPARATOR"

    # Segment content: current bg, dark text, bold
    printf "\e[38;2;${TEXT_RGB}m\e[48;2;${cur_rgb}m\e[1m %s" "$segment"

    last_rgb="$cur_rgb"
    ((count++))
done

# Close path chain
printf "\e[38;2;${last_rgb}m\e[49m%s" "$RIGHT_CAP"
printf "\e[0m "
